const fs = require('fs');
const path = require('path');

const filePath = path.join(__dirname, 'src', 'toolsKnowledge.js');
let content = fs.readFileSync(filePath, 'utf8');

const regex = /# תסריט שיחה\(הופכים קושי לצורך\).*?(?=\n# |\n$)/s;

const newContent = `# תסריט שיחה(הופכים קושי לצורך) (תקשורת מקדמת)
זהו המודל המרכזי למתן משוב וניהול שיחות קשות, המחליף גישה שיפוטית בשיח ממוקד צרכים ופתרונות.
*פילוסופיית הכלי (וילון חובה!):* כשאתה מציע את הכלי הזה, חובה עליך להציג את הפילוסופיה הבאה בתוך וילון HTML (תגית details ו-summary כפי שהוגדר בהנחיות).
ההסבר שיופיע בתוך הוילון הוא: "המטרה העליונה שלנו אינה רק 'לפתור בעיות טכניות', אלא **להצמיח ולגדל מנטורים** בכל שרשרת ההשפעה (מדריך, מנהלת, מורה, תלמיד). כשמתמודדים מול אדם שקשה לו, הגישה אינה להנחית עליו פתרונות, אלא להבין לעומק מה קשה לו ולעודד אותו להגדיר בעצמו מה הוא צריך. ברגע שהוא מגדיר את הצורך, הוא הופך לשותף פעיל ולוקח בעלות על הפתרון. תפקידך משתנה בהתאם לכובע שאתה חובש: **כיועץ:** אתה מברר קודם כל מה הקושי והצורך של המנהלת עצמה. **כמאמן:** אתה מלמד ומתרגל יחד עם המנהלת כיצד לנהל שיח כזה מול העובדים שלה (לברר את הצרכים שלהם). חשוב לזכור את הצד המערכתי: בהתאם להקשר, לעיתים חובה על המנהלת גם להציג את הקושי המערכתי ואת הצורך הבלתי מתפשר של בית הספר (לפני או אחרי שהיא מבררת את צרכי העובד)."
*שלבי השיחה:*
1. ציון עובדתי: הצגת העובדות כפי שהן ללא פרשנות ("כאשר קורה X...").
2. הצגת הקושי: הסבר ברור כיצד המצב מקשה על העבודה או פוגע במערכת.
3. בירור צרכים ושותפות: בדיקה עם הצד השני מה מעכב אותו, ועידודו להגדיר מה הוא צריך ("מה אתה צריך כדי שנוכל להתקדם?").
4. הגדרת הצורך של בית הספר והסכמה על פתרון: חידוד הצורך הבלתי מתפשר של המערכת, וקביעת מנגנון מוסכם ליישום משותף.`;

if (regex.test(content)) {
  content = content.replace(regex, newContent);
  fs.writeFileSync(filePath, content, 'utf8');
  console.log("Regex patch successful!");
} else {
  console.log("Regex didn't match.");
}
