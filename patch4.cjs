if (oldGeminiRegex.test(geminiContent)) {
  geminiContent = geminiContent.replace(oldGeminiRegex, newGemini);
  fs.writeFileSync(geminiPath, geminiContent, 'utf8');
  console.log("Patched gemini.js successfully!");
} else {
  console.log("Could not match oldGeminiRegex in gemini.js");
}

