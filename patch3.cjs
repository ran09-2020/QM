const fs = require('fs');
const path = require('path');

const filePath = path.join(__dirname, 'src', 'toolsKnowledge.js');
let content = fs.readFileSync(filePath, 'utf8');

const regex = /# תסריט שיחה\(הופכים קושי לצורך\).*?(?=\n# |\n$)/s;

const newContent = `# תסריט שיחה(הופכים קושי לצורך) (תקשורת מקדמת)
זהו המודל המרכזי למתן משוב וניהול שיחות קשות, המחליף גישה שיפוטית בשיח ממוקד צרכים ופתרונות.
*פילוסופיית הכלי (וילון חובה!):* כשאתה מציע את הכלי הזה, חובה עליך להציג את הפילוסופיה הבאה בתוך וילון HTML (תגיות details ו-summary). אסור להשתמש בכוכביות בפנים, השתמש רק בתגיות HTML כמו <b> להדגשה ו-<br> לירידת שורה.
דוגמה למבנה הוילון שעליך לייצר (העתק את המבנה הזה בדיוק):
<details>
<summary><b>פילוסופיית הכלי: לגדל מנטורים, לא רק לפתור בעיות</b></summary>
<p>המטרה שלנו אינה רק לפתור את הבעיה הטכנית, אלא <b>להצמיח ולגדל מנטורים</b> בכל דרג (מדריך, מנהלת, מורה, תלמיד).</p>
<p>כשמתמודדים מול אדם שקשה לו, הגישה היא לא "להנחית" פתרונות אינסטנט.<br>
יש להבין לעומק מה קשה לו ולעודד אותו להגדיר בעצמו מה הוא צריך.<br>
ברגע שהוא מגדיר את הצורך, הוא הופך לשותף פעיל ולוקח בעלות על הפתרון.</p>
<p><b>תפקידך משתנה בהתאם לכובע שאתה חובש:</b><br>
- <b>כיועץ:</b> אתה מברר קודם כל מה הקושי והצורך של המנהלת עצמה.<br>
- <b>כמאמן:</b> אתה מלמד ומתרגל יחד עם המנהלת כיצד לברר צרכים מול העובדים שלה.</p>
<p><b>גבולות וצורך מערכתי:</b><br>
לעיתים חובה על המנהלת גם להציג את הקושי המערכתי שלה ואת הצורך הבלתי מתפשר של בית הספר, לפני או אחרי שהיא מבררת את צרכי העובד.</p>
</details>
*שלבי השיחה:*
1. ציון עובדתי: הצגת העובדות כפי שהן ללא פרשנות ("כאשר קורה X...").
2. הצגת הקושי: הסבר ברור כיצד המצב מקשה על העבודה או פוגע במערכת.
3. בירור צרכים ושותפות: בדיקה עם הצד השני מה מעכב אותו, ועידודו להגדיר מה הוא צריך ("מה אתה צריך כדי שנוכל להתקדם?").
4. הגדרת הצורך של בית הספר והסכמה על פתרון: חידוד הצורך הבלתי מתפשר של המערכת, וקביעת מנגנון מוסכם ליישום משותף.`;

if (regex.test(content)) {
  content = content.replace(regex, newContent);
  fs.writeFileSync(filePath, content, 'utf8');
  console.log("Regex patch 3 successful!");
} else {
  console.log("Regex didn't match.");
}
